"""Single-user login for the web UI: magic link by e-mail + HMAC-signed session cookie.

- The login page has one button; the link always goes to REPORT_EMAIL (no address input), at
  most LOGIN_MAILS_PER_HOUR per hour. The token is random (256 bit), stored only as its SHA-256
  hash with a 15-minute expiry, and consumed atomically: it works once.
- Opening the link shows a page with a button; only that POST consumes the token, so mail
  scanners that prefetch links cannot burn it.
- Session cookie: base64url(json{sid, exp}) + "." + HMAC-SHA256, 30 days, HttpOnly, Secure,
  SameSite=Lax. The signing key comes from Secrets Manager (kmlog/web, generated by Terraform).
- CSRF: every POST carries a token = HMAC(key, "csrf:" + sid); the Origin header, when sent,
  must match the host.
"""

from __future__ import annotations

import base64
import hashlib
import hmac
import json
import secrets
from dataclasses import dataclass
from datetime import datetime, timedelta

from ..store import Store

COOKIE = "kmlog_session"
SESSION_DAYS = 30
TOKEN_MINUTES = 15
LOGIN_MAILS_PER_HOUR = 5


def _b64(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode()


def _unb64(text: str) -> bytes:
    return base64.urlsafe_b64decode(text + "=" * (-len(text) % 4))


def token_hash(token: str) -> str:
    return hashlib.sha256(token.encode()).hexdigest()


@dataclass(frozen=True)
class Session:
    sid: str
    expires: datetime


class Auth:
    def __init__(self, key: bytes, store: Store) -> None:
        if len(key) < 32:
            raise ValueError("session signing key must be at least 32 bytes")
        self.key = key
        self.store = store

    def _sign(self, payload: str) -> str:
        return _b64(hmac.new(self.key, payload.encode(), hashlib.sha256).digest())

    # --- magic link -----------------------------------------------------------------------

    def may_send_login_mail(self, now: datetime) -> bool:
        hour = now.strftime("%Y%m%d%H")
        used = self.store.increment_counter(f"login-mail:{hour}", now + timedelta(hours=2))
        return used <= LOGIN_MAILS_PER_HOUR

    def new_login_token(self, now: datetime) -> str:
        token = secrets.token_urlsafe(32)
        self.store.put_login_token(token_hash(token), now + timedelta(minutes=TOKEN_MINUTES))
        return token

    def consume_login_token(self, token: str, now: datetime) -> bool:
        if not token or len(token) > 200:
            return False
        return self.store.consume_login_token(token_hash(token), now)

    # --- session --------------------------------------------------------------------------

    def new_session_cookie(self, now: datetime) -> str:
        expires = now + timedelta(days=SESSION_DAYS)
        payload = _b64(
            json.dumps({"sid": secrets.token_urlsafe(16), "exp": int(expires.timestamp())}).encode()
        )
        value = f"{payload}.{self._sign(payload)}"
        return (
            f"{COOKIE}={value}; Max-Age={SESSION_DAYS * 86400}; Path=/; "
            "HttpOnly; Secure; SameSite=Lax"
        )

    @staticmethod
    def clear_cookie() -> str:
        return f"{COOKIE}=; Max-Age=0; Path=/; HttpOnly; Secure; SameSite=Lax"

    def session(self, cookies: dict[str, str], now: datetime) -> Session | None:
        value = cookies.get(COOKIE, "")
        payload, _, sig = value.partition(".")
        if not payload or not sig or not hmac.compare_digest(sig, self._sign(payload)):
            return None
        try:
            data = json.loads(_unb64(payload))
            expires = datetime.fromtimestamp(int(data["exp"]), tz=now.tzinfo)
            sid = str(data["sid"])
        except (ValueError, KeyError, TypeError):
            return None
        if expires <= now:
            return None
        return Session(sid=sid, expires=expires)

    # --- CSRF -----------------------------------------------------------------------------

    def csrf_token(self, session: Session) -> str:
        return self._sign(f"csrf:{session.sid}")

    def check_csrf(self, session: Session, token: str | None) -> bool:
        return bool(token) and hmac.compare_digest(token, self.csrf_token(session))
