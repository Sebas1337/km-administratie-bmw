"""Web UI Lambda behind a Function URL (see kmlog/web/app.py).

Environment: TABLE_NAME, VEHICLE_ID, REPORT_EMAIL, WEB_SECRET_ID, SECRET_ID, QUOTA_LIMIT,
GEOCODER_URL / GEOCODER_CONTACT / GEOCODER_COUNTRIES (address search on the Instellingen page;
GEOCODER_URL "off" disables it). The
session signing key is read once per container from Secrets Manager (kmlog/web, generated by
Terraform). The CarData token state (SECRET_ID) is read per request, for the Auto page.
"""

from __future__ import annotations

import json
from datetime import UTC, datetime, timedelta
from functools import cache

from .. import cardata
from ..geocode import DEFAULT_CONTACT, DEFAULT_URL, NominatimGeocoder
from . import env, log_event, send_mail
from .poller import quota_guard


def _geocoder(store) -> NominatimGeocoder | None:
    url = env("GEOCODER_URL", DEFAULT_URL)
    if url == "off":
        return None

    def allow_request() -> bool:  # the public Nominatim allows 1 request per second in total
        now = datetime.now(UTC)
        return (
            store.increment_counter(f"geocode:{int(now.timestamp())}", now + timedelta(minutes=5))
            == 1
        )

    return NominatimGeocoder(
        base_url=url,
        contact=env("GEOCODER_CONTACT", DEFAULT_CONTACT),
        countries=env("GEOCODER_COUNTRIES", "nl"),
        allow_request=allow_request,
    )


@cache
def _app():
    import boto3

    from ..store.dynamodb import DynamoDbStore
    from ..web.app import WebApp
    from ..web.auth import Auth

    secret = boto3.client("secretsmanager").get_secret_value(SecretId=env("WEB_SECRET_ID"))
    key = json.loads(secret["SecretString"])["session_key"].encode()
    store = DynamoDbStore(env("TABLE_NAME", "kmlog-data"))
    ses = boto3.client("ses")
    address = env("REPORT_EMAIL")
    tokens = cardata.SecretsManagerTokenStore(env("SECRET_ID", "kmlog/cardata"))
    quota = int(env("QUOTA_LIMIT", "40"))
    return WebApp(
        store,
        Auth(key, store, address),
        env("VEHICLE_ID", "car"),
        lambda subject, body: send_mail(ses, address, subject, body),
        cardata=lambda: cardata.CarDataClient(tokens, before_api_call=quota_guard(store, quota)),
        quota_limit=quota,
        geocoder=_geocoder(store),
    )


def handler(event, context, *, app=None) -> dict:
    app = app or _app()
    response = app(event)
    http = event.get("requestContext", {}).get("http", {})
    # path only: query strings may carry a login token
    log_event(
        event="web",
        method=http.get("method"),
        path=event.get("rawPath"),
        status=response["statusCode"],
    )
    return response
